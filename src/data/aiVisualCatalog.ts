export function getVisualBundleForLook(
  look: { lookName?: string; styleConcept?: string; outfit?: { top?: string; bottom?: string }; colourPalette?: { name: string; hex: string }[]; userPrompt?: string },
  variationSeed: number = 0
): AILookVisualBundle {
  const text = `${look.lookName || ''} ${look.styleConcept || ''} ${look.outfit?.top || ''} ${look.outfit?.bottom || ''} ${look.userPrompt || ''} ${look.colourPalette?.map(c => c.name).join(' ') || ''}`.toLowerCase();

  let categoryKey = 'green';

  if (text.includes('yellow') || text.includes('marigold') || text.includes('haldi') || text.includes('ochre') || text.includes('amber') || text.includes('college')) {
    categoryKey = 'yellow';
  } else if (text.includes('wine') || text.includes('crimson') || text.includes('red') || text.includes('maroon') || text.includes('zardozi') || text.includes('banarasi')) {
    categoryKey = 'crimson';
  } else if (text.includes('blue') || text.includes('navy') || text.includes('sapphire') || text.includes('indo-western') || text.includes('dhoti') || text.includes('trench')) {
    categoryKey = 'navy';
  } else if (text.includes('pink') || text.includes('rose') || text.includes('blush') || text.includes('pastel') || text.includes('peach')) {
    categoryKey = 'blush';
  } else if (text.includes('ivory') || text.includes('white') || text.includes('mulmul') || text.includes('minimal') || text.includes('linen') || text.includes('ecru')) {
    categoryKey = 'ivory';
  } else {
    // Check color palette hex if text didn't match
    const firstHex = look.colourPalette?.[0]?.hex?.toLowerCase() || '';
    if (firstHex.includes('e08') || firstHex.includes('f2c')) categoryKey = 'yellow';
    else if (firstHex.includes('6e2') || firstHex.includes('8e3')) categoryKey = 'crimson';
    else if (firstHex.includes('1d3') || firstHex.includes('2a4')) categoryKey = 'green';
    else if (firstHex.includes('faf') || firstHex.includes('efe')) categoryKey = 'ivory';
  }

  const bundles = AI_VISUAL_CATALOG[categoryKey] || AI_VISUAL_CATALOG.green;
  const index = Math.abs(variationSeed) % bundles.length;
  return bundles[index];
}
